// Per Categories.md, each direction stores:
//   typography – allowed pairing categories (Stage 1 list, verbatim). An entry is
//                either a category id or { cat, body, thin } to constrain further.
//   palettes   – allowed moods (Stage 2 list, verbatim), optionally "mood:tag".
//   surfaces   – one id = pre-set by the direction; 2–3 = visible choice
//                (only Minimal, Corporate and Scandinavian get a choice).
//   components – variant families excluded per category.
//   sections   – variant tags excluded / preferred.
//   motion     – allowed presets (file defaults, extended from each description).
//   defaults   – the recommended pick for every stage.

