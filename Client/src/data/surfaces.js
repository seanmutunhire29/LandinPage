/** none / sm / md / lg / xl / pill, derived from a base radius in px. */
export function radiusScale(base) {
  return {
    none: 0,
    sm: Math.round(base * 0.5),
    md: base,
    lg: Math.round(base * 1.5),
    xl: base * 2,
    pill: 9999,
  }
}
